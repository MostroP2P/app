          ),
        ),
  );

  Widget _form(AppLocalizations l10n, BigInt? sats, TradeInfo? trade) {
    final check = _check(sats);
    final error = _errorReadout();
    final validation = _validationText(l10n, check);
    return Column(
      crossAxisAlignment: CrossAxisAlignment.stretch,
      children: [
        // Sats amount calculated by the daemon (arrives in the take /
        // add-invoice reply and lands in the trade record).
        if (sats != null) ...[
          InvoiceHeroCard(
            label: l10n.invoiceYouReceiveLabel,
            sats: sats.toInt(),
            semanticsLabel: l10n.invoiceReceiveSemantics(
              formatInvoiceSats(sats.toInt(), l10n.localeName),
            ),
            contextLine: _heroContext(l10n, trade),
            automationId: AutomationIds.invoiceAmount,
            automationLabel: sats.toString(),
          ),
          const SizedBox(height: 12),
        ],
        ValueListenableBuilder<Duration?>(
          valueListenable: invoiceRemaining,
          builder:
              (context, remaining, _) =>
                  remaining == null
                      ? const SizedBox.shrink()
                      : Padding(
                        padding: const EdgeInsets.only(bottom: 12),
                        child: InvoiceTimeBand(
                          remaining: remaining,
                          window: ref.watch(invoiceStepWindowProvider),
                          sentence: l10n.invoiceTimeToSend,
                          hours: l10n.invoiceCountdownHours,
                          elapsed: stepElapsedNotice(
                            l10n,
                            buyerStep: true,
                            kind: trade?.order.kind,
                          ),
                        ),
                      ),
        ),
        InvoiceInputField(
          controller: _invoiceController,
          focusNode: _focus,
          onChanged: _onInputChanged,
          onPaste: _clipboardHasText ? _paste : null,
          onScan: _scan,
          validSats: check is InvoiceCheckValid ? check.sats : null,
          isValid: check is InvoiceCheckValid || check is InvoiceCheckAddress,
          isAddress: check is InvoiceCheckAddress,
          // A real verdict, not whatever fills the readout slot: the
          // waiting note shares it and is not an error (PR #617 review).
          hasError: _lastError != null || check is InvoiceCheckError,
        ),
        if (error != null) ...[
          const SizedBox(height: 8),
          error,
        ] else if (validation != null) ...[
          const SizedBox(height: 8),
          invoiceCheckRow(check: check, sentence: validation),
        ],
        // Always drawn: the order's ID row is in it (DS-CMP-22), and the
        // counterpart rows join once the trade loads (DS-CMP-24).
        const SizedBox(height: 12),
        OrderDataCard(
          rows: [
            if (trade != null) ..._counterpartRows(l10n, trade),
            OrderIdRow(
              orderId: widget.orderId,
              automationId: AutomationIds.invoiceOrderId,
            ),
          ],
        ),
        const Spacer(),
        const SizedBox(height: 16),
        InvoicePrimaryButton(
          icon: Icons.bolt,
          label: l10n.invoiceSendButton,
          busy: _submitting,
          onPressed: _canSubmit(sats) ? () => _submit(ref) : null,
        ).withAutomationId(AutomationIds.invoiceSubmit),
        const SizedBox(height: 4),
        InvoiceCancelLink(
          label: l10n.invoiceCancelTrade,
          // It cancels the trade, not just the screen (DS-CMP-20).
          danger: true,
          onPressed: (_submitting || _canceling) ? null : _cancelOrder,
        ).withAutomationId(AutomationIds.invoiceCancel),
      ],
    );
  }

  /// The validation row's sentence, or null when the row is not drawn.
  String? _validationText(AppLocalizations l10n, InvoiceCheck check) =>
      switch (check) {
        InvoiceCheckNone() ||
        InvoiceCheckPending() ||
        InvoiceCheckUnverified() => null,
        InvoiceCheckAddress() => l10n.invoiceValidAddress,
        InvoiceCheckValid(:final sats) => l10n.invoiceValidInvoice(
          formatInvoiceSats(sats, l10n.localeName),
        ),
        InvoiceCheckError(
          :final problem,
          :final actualMsat,
          :final expectedSats,
          :final invoiceNetwork,
          :final nodeNetwork,
          :final minRemainingSecs,
        ) =>
          switch (problem) {
            InvoiceProblem.wrongAmount => l10n.invoiceErrorWrongAmount(
              formatInvoiceMsat(actualMsat ?? 0, l10n.localeName),
              formatInvoiceSats(expectedSats ?? 0, l10n.localeName),
            ),
            InvoiceProblem.wrongNetwork => l10n.invoiceErrorWrongNetwork(
              invoiceNetwork ?? '?',
              nodeNetwork ?? '?',
            ),
            InvoiceProblem.expired => l10n.invoiceErrorExpired,
            InvoiceProblem.expiresTooSoon => l10n.invoiceErrorExpiresTooSoon(
              ((minRemainingSecs ?? 0) / 60).ceil().toString(),
            ),
            InvoiceProblem.malformed => l10n.invoiceErrorMalformed,
            InvoiceProblem.unrecognized => l10n.invoiceErrorUnrecognized,
          },
      };

  /// `≈ 312 ARS · Bitcoin Bolivia`: what the sats are worth, and the node
  /// that settles the trade (not the counterpart).
  String? _heroContext(AppLocalizations l10n, TradeInfo? trade) {
    final fiat = trade == null ? null : formatInvoiceFiat(l10n, trade);
    final node = ref.watch(activeNodeNameProvider);
    final parts = [if (fiat != null) '≈ $fiat', if (node != null) node];
    return parts.isEmpty ? null : parts.join(' · ');
  }

  List<Widget> _counterpartRows(AppLocalizations l10n, TradeInfo trade) {
    final fiat = formatInvoiceFiat(l10n, trade);
    return [
      invoiceCounterpartRow(ref, l10n, trade, l10n.invoiceSellerLabel),
      if (fiat != null)
        invoiceFiatRow(
          l10n.invoiceYouPayLabel,
          fiat,
          trade.order.paymentMethod,
        ),
    ];
  }
}

/// What the invoice checker needs from the node, plus a key that changes
/// whenever any of it does.
typedef _NodeContext =
    ({
      List<String> networks,
      int? minRemainingSecs,
      String key,
      bool factsKnown,
    });
